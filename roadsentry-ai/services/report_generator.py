"""
RoadSentry AI - Professional Report Generation Service
Generates PDF, DOCX, JSON, and CSV reports with strict mandatory audit disclaimers.
"""
from typing import Dict, Any, List, Optional
import io
import json
import csv
from datetime import datetime

try:
    from reportlab.lib.pagesizes import letter
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib import colors
    REPORTLAB_AVAILABLE = True
except ImportError:
    REPORTLAB_AVAILABLE = False

try:
    import docx
    from docx.shared import Inches, Pt, RGBColor
    DOCX_AVAILABLE = True
except ImportError:
    DOCX_AVAILABLE = False


class ReportGenerator:
    """
    Generates downloadable audit dossiers and road inspection reports.
    Always includes mandatory banner:
    'AI-Assisted Draft Audit Report — Subject to Professional Auditor Review.'
    """

    MANDATORY_DISCLAIMER = (
        "CONFIDENTIAL & DRAFT: This document is an AI-assisted engineering and infrastructure audit report generated by RoadSentry AI. "
        "It provides preliminary decision-support indicators based on automated computer vision inference and criteria comparison. "
        "It DOES NOT constitute an official audit opinion or statutory engineering certification. "
        "All observations and findings must undergo on-site physical verification by certified public auditors and structural engineers."
    )

    @staticmethod
    def generate_json_export(session_data: Dict[str, Any]) -> str:
        """Export session data as formatted JSON."""
        return json.dumps(session_data, indent=2, default=str)

    @staticmethod
    def generate_csv_inspections(inspections: List[Dict[str, Any]]) -> str:
        """Export inspections as CSV."""
        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow([
            "Inspection_ID",
            "Filename",
            "Dzongkhag",
            "Road_Classification",
            "Risk_Level",
            "Risk_Score",
            "Defect_Count",
            "Defect_Codes",
            "Surface_Damage_Pct",
            "Latitude",
            "Longitude",
            "Created_At"
        ])
        for insp in inspections:
            detections = insp.get("detections", [])
            codes = ";".join([d.get("class_code", "") for d in detections])
            coords = insp.get("coordinates") or {}
            writer.writerow([
                insp.get("id"),
                insp.get("filename"),
                insp.get("dzongkhag"),
                insp.get("road_class"),
                insp.get("risk_assessment", {}).get("level"),
                insp.get("risk_assessment", {}).get("score"),
                len(detections),
                codes,
                insp.get("risk_assessment", {}).get("factor_breakdown", {}).get("total_area_pct", 0.0),
                coords.get("lat", ""),
                coords.get("lon", ""),
                insp.get("created_at")
            ])
        return output.getvalue()

    @staticmethod
    def generate_docx_report(
        session_summary: Dict[str, Any],
        inspections: List[Dict[str, Any]],
        findings: List[Dict[str, Any]]
    ) -> bytes:
        """Generate a complete Word document (.docx) report."""
        if not DOCX_AVAILABLE:
            raise RuntimeError("python-docx is not installed.")

        doc = docx.Document()
        
        # Title
        title_p = doc.add_paragraph()
        title_run = title_p.add_run("RoadSentry AI — Infrastructure Audit Report")
        title_run.font.size = Pt(22)
        title_run.font.bold = True
        title_run.font.color.rgb = RGBColor(11, 44, 90)

        subtitle_p = doc.add_paragraph()
        sub_run = subtitle_p.add_run("Automated Multimodal Road Hazard & Infrastructure Audit Intelligence — Kingdom of Bhutan")
        sub_run.font.size = Pt(12)
        sub_run.font.italic = True

        # Disclaimer Box
        disc_p = doc.add_paragraph()
        disc_run = disc_p.add_run(ReportGenerator.MANDATORY_DISCLAIMER)
        disc_run.font.size = Pt(9.5)
        disc_run.font.bold = True
        disc_run.font.color.rgb = RGBColor(180, 50, 50)

        doc.add_heading("1. Executive Summary & Session Metrics", level=1)
        summary_table = doc.add_table(rows=1, cols=4)
        hdr_cells = summary_table.rows[0].cells
        hdr_cells[0].text = "Total Inspections"
        hdr_cells[1].text = "Total YOLO Detections"
        hdr_cells[2].text = "Critical Risk Hazards"
        hdr_cells[3].text = "Draft 5C Findings"
        
        row_cells = summary_table.add_row().cells
        row_cells[0].text = str(session_summary.get("total_inspections", 0))
        row_cells[1].text = str(session_summary.get("total_detections", 0))
        row_cells[2].text = str(session_summary.get("risk_counts", {}).get("CRITICAL", 0))
        row_cells[3].text = str(len(findings))

        doc.add_heading("2. Verified Visual Inspection Evidence", level=1)
        for insp in inspections:
            p = doc.add_paragraph()
            p.add_run(f"Evidence ID: {insp.get('id')} — File: {insp.get('filename')}\n").bold = True
            p.add_run(f"Location: {insp.get('dzongkhag', 'N/A')} | Classification: {insp.get('road_class', 'N/A')}\n")
            p.add_run(f"Assessed Risk: {insp.get('risk_assessment', {}).get('level')} ({insp.get('risk_assessment', {}).get('score')} pts)\n")
            p.add_run(f"Defect Count: {len(insp.get('detections', []))}\n")
            p.add_run(f"Engineering Justification: {insp.get('risk_assessment', {}).get('explanation')}\n")

        doc.add_heading("3. Structured 5C Infrastructure Audit Findings", level=1)
        if not findings:
            doc.add_paragraph("No 5C audit findings generated in active session.")
        else:
            for idx, f in enumerate(findings):
                doc.add_heading(f"Finding {idx+1}: {f.get('title')}", level=2)
                p = doc.add_paragraph()
                p.add_run("Criteria (Standard): ").bold = True
                p.add_run(f"{f.get('criteria')}\n")
                p.add_run("Condition (Observed): ").bold = True
                p.add_run(f"{f.get('condition')}\n")
                p.add_run("Cause: ").bold = True
                p.add_run(f"{f.get('cause')}\n")
                p.add_run("Consequence / Risk: ").bold = True
                p.add_run(f"{f.get('consequence')}\n")
                p.add_run("Corrective Action: ").bold = True
                p.add_run(f"{f.get('recommendation')}\n")
                p.add_run("Verification Status: ").bold = True
                p.add_run(f"{f.get('verification_status')}\n")

        bio = io.BytesIO()
        doc.save(bio)
        return bio.getvalue()

    @staticmethod
    def generate_pdf_report(
        session_summary: Dict[str, Any],
        inspections: List[Dict[str, Any]],
        findings: List[Dict[str, Any]]
    ) -> bytes:
        """Generate formatted PDF audit dossier using ReportLab."""
        if not REPORTLAB_AVAILABLE:
            raise RuntimeError("reportlab is not installed.")

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=letter, leftMargin=36, rightMargin=36, topMargin=36, bottomMargin=36)
        styles = getSampleStyleSheet()

        title_style = ParagraphStyle(
            'TitleStyle',
            parent=styles['Heading1'],
            fontSize=18,
            textColor=colors.HexColor("#0f172a"),
            spaceAfter=6
        )
        subtitle_style = ParagraphStyle(
            'SubStyle',
            parent=styles['Normal'],
            fontSize=10,
            textColor=colors.HexColor("#0369a1"),
            spaceAfter=12
        )
        disclaimer_style = ParagraphStyle(
            'DiscStyle',
            parent=styles['Normal'],
            fontSize=8,
            textColor=colors.HexColor("#b91c1c"),
            backColor=colors.HexColor("#fef2f2"),
            borderPadding=6,
            spaceAfter=14
        )
        h2_style = ParagraphStyle(
            'H2Style',
            parent=styles['Heading2'],
            fontSize=13,
            textColor=colors.HexColor("#0f172a"),
            spaceBefore=10,
            spaceAfter=6
        )
        body_style = ParagraphStyle(
            'BodyStyle',
            parent=styles['Normal'],
            fontSize=9,
            spaceAfter=4
        )

        elements = []
        elements.append(Paragraph("RoadSentry AI — Infrastructure Audit Dossier", title_style))
        elements.append(Paragraph("Kingdom of Bhutan Road Safety & Performance Audit Intelligence", subtitle_style))
        elements.append(Paragraph(ReportGenerator.MANDATORY_DISCLAIMER, disclaimer_style))

        # Metrics Table
        elements.append(Paragraph("1. Session Metrics Overview", h2_style))
        summary_data = [
            ["Metric", "Value", "Metric", "Value"],
            ["Total Inspections", str(session_summary.get("total_inspections", 0)), "Critical Hazards", str(session_summary.get("risk_counts", {}).get("CRITICAL", 0))],
            ["YOLO Detections", str(session_summary.get("total_detections", 0)), "Audit Findings", str(len(findings))]
        ]
        t = Table(summary_data, colWidths=[130, 130, 130, 130])
        t.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor("#0f172a")),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 9),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ('PADDING', (0, 0), (-1, -1), 4),
        ]))
        elements.append(t)
        elements.append(Spacer(1, 12))

        # Findings section
        elements.append(Paragraph("2. 5C Audit Findings Framework", h2_style))
        if not findings:
            elements.append(Paragraph("No 5C audit findings created in active session.", body_style))
        else:
            for idx, f in enumerate(findings):
                elements.append(Paragraph(f"<b>Finding #{idx+1}: {f.get('title')}</b>", body_style))
                elements.append(Paragraph(f"<b>Criteria:</b> {f.get('criteria')}", body_style))
                elements.append(Paragraph(f"<b>Condition:</b> {f.get('condition')}", body_style))
                elements.append(Paragraph(f"<b>Cause:</b> {f.get('cause')}", body_style))
                elements.append(Paragraph(f"<b>Consequence:</b> {f.get('consequence')}", body_style))
                elements.append(Paragraph(f"<b>Recommendation:</b> {f.get('recommendation')}", body_style))
                elements.append(Paragraph(f"<b>Status:</b> {f.get('verification_status')}", body_style))
                elements.append(Spacer(1, 8))

        doc.build(elements)
        return buffer.getvalue()
